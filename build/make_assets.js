// Embeds the character GLBs as base64 so the game runs from a single HTML file.
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'assets');
const files = ['stephen_curry.glb', 'lebron_james.glb', 'michael_jordan.glb'];
let out = '// Generated by build/make_assets.js — the supplied character GLBs, base64-encoded.\nconst HOOP_ASSETS = {\n';
for (const f of files) out += `  ${JSON.stringify(f)}: ${JSON.stringify(fs.readFileSync(path.join(dir, f)).toString('base64'))},\n`;
out += '};\n';
fs.writeFileSync(path.join(__dirname, '..', 'src', 'assets.gen.js'), out);
console.log('assets.gen.js', (out.length / 1024).toFixed(0), 'KB');
